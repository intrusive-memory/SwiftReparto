// TestFixture.swift
// SwiftRepartoTests
//
// Sortie 13: the one door every test uses to reach a pinned fixture.
//
// All four fixtures under `Fixtures/` are pinned as immutable bytes — the
// `confessions-CAST.md` and `all-fields-CAST.md` documents are SHA-256 anchors
// for WU-4's acceptance gates, and a fixture the test suite can rewrite proves
// nothing. So no test names a path outside the package: every fixture is
// reached through `Bundle.module`, which resolves against the test bundle's
// `Fixtures/` resource copy (`Package.swift`'s `.copy("Fixtures")`), not
// against the source checkout. That is also what makes these fixtures
// reachable under the iOS Simulator destination, where there is no source
// tree to walk up from with `#filePath`.
//
// This type only *reads*. It has no `write`, no `FileManager.default.write`,
// and touches nothing under `Fixtures/` — see Sortie 13's exit criterion on
// that point.

import Foundation

/// A pinned fixture under `Tests/SwiftRepartoTests/Fixtures/`, reached through
/// `Bundle.module`.
enum TestFixture: String {

  /// The import-path fixture (Sortie 12/13): a trimmed but faithful
  /// `PROJECT.md`, three characters, scalar `voices`, and THE PRACTITIONER's
  /// ~400-character `bio`.
  case confessionsProjectMD = "confessions-PROJECT.md"

  /// The RQ-11 SHA-256 anchor: `confessions-PROJECT.md`, imported and
  /// generated by this library, with a hand-written body appended. Committed
  /// as bytes and never regenerated.
  case confessionsCastMD = "confessions-CAST.md"

  /// Exercises every declared `CastMember` field plus an undeclared key and a
  /// nested `appearance:` block — the standing proof that D-3's deferral is
  /// lossless.
  case allFieldsCastMD = "all-fields-CAST.md"

  /// A valid cast document with no `schemaVersion` key, exercising D-5's
  /// legacy path. Deliberately **not** in emitted form — see the file's own
  /// header comment.
  case legacyUnversionedCastMD = "legacy-unversioned-CAST.md"

  /// The fixture's location inside the test bundle's resource copy.
  ///
  /// - Throws: If the fixture is missing from the bundle — which would mean
  ///   either the file was not committed or `Package.swift`'s `resources:`
  ///   declaration stopped copying it.
  func url() throws -> URL {
    let name = (rawValue as NSString).deletingPathExtension
    let fileExtension = (rawValue as NSString).pathExtension
    guard
      let url = Bundle.module.url(
        forResource: name, withExtension: fileExtension, subdirectory: "Fixtures")
    else {
      throw TestFixtureError.notFound(rawValue)
    }
    return url
  }

  /// The fixture's contents, decoded as UTF-8.
  func contents() throws -> String {
    try String(contentsOf: url(), encoding: .utf8)
  }
}

/// Raised when a fixture named by ``TestFixture`` cannot be located in the
/// test bundle.
enum TestFixtureError: Error, CustomStringConvertible {
  case notFound(String)

  var description: String {
    switch self {
    case .notFound(let name):
      return "Fixture '\(name)' was not found via Bundle.module in subdirectory 'Fixtures'."
    }
  }
}
